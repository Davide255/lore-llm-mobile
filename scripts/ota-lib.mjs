// Pure helpers for scripts/publish-ota.mjs (see docs/OTA.md). No I/O side effects
// beyond reading the files they are given, so they can be unit-tested.
import { createHash, createSign, randomUUID } from "node:crypto";
import { readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";

const CONTENT_TYPES = {
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  gif: "image/gif",
  webp: "image/webp",
  svg: "image/svg+xml",
  ttf: "font/ttf",
  otf: "font/otf",
  json: "application/json",
  mp3: "audio/mpeg",
  mp4: "video/mp4",
  ogg: "audio/ogg",
  wav: "audio/wav",
};

export const contentTypeFor = (ext) =>
  CONTENT_TYPES[String(ext).replace(/^\./, "").toLowerCase()] ??
  "application/octet-stream";

export const md5Hex = (buffer) => createHash("md5").update(buffer).digest("hex");

// Expo wants the SHA-256 as base64url without padding.
export const sha256Base64Url = (buffer) =>
  createHash("sha256")
    .update(buffer)
    .digest("base64")
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/, "");

/*
  Builds an Expo Updates protocol v1 manifest from an `expo export` directory.
  Assets are addressed by their md5 (key) so the same file is never re-uploaded.
  Returns the manifest plus the local files that must exist on the server.
*/
export const buildManifest = ({
  exportDir,
  platform,
  runtimeVersion,
  baseUrl,
  channel,
  expoConfig,
  version,
  id = randomUUID(),
  createdAt = new Date().toISOString(),
}) => {
  const metadata = JSON.parse(
    readFileSync(path.join(exportDir, "metadata.json"), "utf8"),
  );
  const platformMeta = metadata.fileMetadata?.[platform];
  if (!platformMeta) throw new Error(`No ${platform} export in metadata.json`);

  const assetsBase = `${baseUrl}/${channel}/${platform}/assets`;
  const files = new Map(); // remote name -> local path

  const describe = (relPath, ext, contentType) => {
    const local = path.join(exportDir, relPath);
    const data = readFileSync(local);
    const key = md5Hex(data);
    // Keep the extension in the remote name so the server sends a sane MIME type.
    const remote = ext ? `${key}.${ext}` : key;
    files.set(remote, local);
    return {
      hash: sha256Base64Url(data),
      key,
      ...(ext ? { fileExtension: `.${ext}` } : {}),
      contentType: contentType ?? contentTypeFor(ext),
      url: `${assetsBase}/${remote}`,
    };
  };

  const launchAsset = describe(platformMeta.bundle, "hbc", "application/javascript");
  // The launch asset must not carry fileExtension in the manifest.
  delete launchAsset.fileExtension;

  const assets = platformMeta.assets.map((a) =>
    describe(a.path, a.ext, undefined),
  );

  const manifest = {
    id,
    createdAt,
    runtimeVersion,
    launchAsset,
    assets,
    metadata: {},
    extra: { expoClient: expoConfig, otaVersion: version },
  };
  return { manifest, files };
};

// RSA-SHA256 (rsa-v1_5-sha256) over the exact manifest body, as an SFV dictionary.
export const signManifest = (manifestBody, privateKeyPem, keyid = "main") => {
  const sig = createSign("RSA-SHA256")
    .update(manifestBody)
    .sign(privateKeyPem, "base64");
  return `sig="${sig}", keyid="${keyid}"`;
};

// Per-manifest header, written next to manifest.json (ota-server/.htaccess has the rest).
export const signatureHtaccess = (signatureHeader) =>
  `# Generated by scripts/publish-ota.mjs: do not edit.\n` +
  `<FilesMatch "^manifest\\.json$">\n` +
  `  Header set expo-signature '${signatureHeader}'\n` +
  `</FilesMatch>\n`;

// "1.0.0" + now + sha -> "1.0.0-ota.d20261020t2230.gabc1234" (same scheme as the Athly apps).
export const defaultVersion = (pkgVersion, sha = "nogit", now = new Date()) => {
  const stamp = now.toISOString().replace(/[-:]/g, "").slice(0, 13).toLowerCase();
  return `${pkgVersion}-ota.d${stamp}.g${sha}`;
};

export const SEMVER =
  /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(-[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?$/;

/*
  Native fingerprint: everything that ends up in the store binary and that an OTA
  bundle cannot change. If it differs from the one recorded for the current
  runtimeVersion, a bundle published under that runtimeVersion would reach builds
  that cannot run it, so publishing must stop until runtimeVersion is bumped
  (docs/OTA.md). Pure-JS dependencies (mathjax-full, punycode...) are ignored;
  app version and build number are too.
*/
const NATIVE_DEP = /^(expo($|-)|@expo\/|react($|-)|@react-native)/;

// Hashes the files below the given directories (native modules, config plugins).
const hashTrees = (rootDir, dirs) => {
  const h = createHash("sha256");
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      if (name === "node_modules" || name === ".DS_Store") continue;
      const full = path.join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else h.update(path.relative(rootDir, full)).update(readFileSync(full));
    }
  };
  for (const d of dirs) {
    try {
      walk(path.join(rootDir, d));
    } catch (e) {
      if (e.code !== "ENOENT") throw e;
    }
  }
  return h.digest("hex");
};

export const nativeFingerprintInput = ({ pkg, expo, rootDir, trees = ["modules", "plugins"] }) => {
  const deps = Object.fromEntries(
    Object.entries(pkg.dependencies ?? {})
      .filter(([name]) => NATIVE_DEP.test(name))
      .sort(([a], [b]) => (a < b ? -1 : 1)),
  );
  const { buildNumber: _b, ...ios } = expo.ios ?? {};
  const { versionCode: _v, ...android } = expo.android ?? {};
  return {
    deps,
    plugins: expo.plugins ?? [],
    ios,
    android,
    newArchEnabled: expo.newArchEnabled ?? null,
    localNative: rootDir ? hashTrees(rootDir, trees) : null,
  };
};

export const nativeFingerprint = (input) =>
  createHash("sha256").update(JSON.stringify(nativeFingerprintInput(input))).digest("hex");
